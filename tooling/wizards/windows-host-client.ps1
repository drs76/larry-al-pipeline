"@
  if (-not (Test-Path $bashrc) -or -not (Select-String -Path $bashrc -Pattern ([regex]::Escape($marker)) -Quiet)) {
    Add-Content -Path $bashrc -Value $block; Ok "workflow env appended to $bashrc"
  } else { Ok 'env block already present' }
  # python3 shim (LF, no BOM) — scripts that call python3 directly
  $shim = Join-Path $env:USERPROFILE '.local\bin\python3'
  [IO.File]::WriteAllText($shim, "#!/bin/sh`nexec python `"`$@`"`n")
  Ok 'python3 shim written'; Say 'in a Git Bash tab: alw help / gow help / csw help'
  Mark 'bashrc'
}

